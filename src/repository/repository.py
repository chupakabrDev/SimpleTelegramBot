import dataclasses
from abc import ABC, abstractmethod
from typing import TypeVar, Generic, Optional, cast, Any

from sqlalchemy import select, func, delete
from sqlalchemy.orm import DeclarativeBase, sessionmaker, Session, MappedAsDataclass, Mapped, mapped_column

TElement = TypeVar('TElement', bound='KeyedMixin')

class Repository(ABC, Generic[TElement]):

    def __init__(self, generated: bool = True):
        self.generated = generated

    @abstractmethod
    def query_by(self, column: Mapped, value) -> list[TElement]:
        raise NotImplementedError

    @abstractmethod
    def query_page(self, page: int, size: int, **filters: Any) -> list[TElement]:
        raise NotImplementedError

    @abstractmethod
    def update_or_create(self, element: TElement) -> int:
        raise NotImplementedError

    @abstractmethod
    def retrieve(self, key: int) -> Optional[TElement]:
        raise NotImplementedError

    @abstractmethod
    def delete(self, key: int) -> None:
        raise NotImplementedError

    @abstractmethod
    def delete_by(self, column: Mapped, value) -> None:
        raise NotImplementedError

    @abstractmethod
    def count(self) -> int:
        raise NotImplementedError

    @abstractmethod
    def count_filtered(self, **filters: Any) -> int:
        raise NotImplementedError

    @abstractmethod
    def exists_by(self, column: Mapped, value) -> bool:
        raise NotImplementedError

class Base(MappedAsDataclass, DeclarativeBase):
    pass


class KeyedMixin(MappedAsDataclass):
    key: Mapped[Optional[int]] = mapped_column(
        primary_key=True,
        autoincrement=True,
        default=None,
        init=False,
    )


class SQLAlchemyRepository(Repository[TElement]):

    def __init__(
        self,
        session_factory: sessionmaker[Session],
        model: type[TElement],
        generated: bool = True,
    ):
        super().__init__(generated)
        self._session_factory = session_factory
        self._model = model

    def query_by(self, column: Mapped, value) -> list[TElement]:
        stmt = select().where(column == value).select_from(self._model)
        with self._session_factory() as session:
            return list(session.scalars(stmt))

    def query_page(
            self,
            page: int,
            size: int,
            **filters: Any,
    ) -> list[TElement]:
        stmt = (
            select(self._model)
            .order_by(self._model.key)
            .limit(size)
            .offset(page * size)
        )
        for name, value in filters.items():
            stmt = stmt.where(getattr(self._model, name) == value)

        with self._session_factory() as session:
            return list(session.scalars(stmt))

    def exists_by(self, column: Mapped, value) -> bool:
        base_stmt = select(self._model).where(column == value)
        stmt = select(base_stmt.exists())

        with self._session_factory() as session:
            return bool(session.scalar(stmt))

    @staticmethod
    def generate_key(element: TElement, session) -> int:
        session.add(element)
        session.flush()

        assert element.key is not None, "The key was not generated by the database"
        return int(element.key)

    def update_or_create(self, element: TElement) -> int:
        with self._session_factory() as session, session.begin():
            pk = element.key
            is_new = pk is None or pk < 0

            if is_new:
                if not self.generated:
                    raise ValueError(
                        f"{type(element).__name__}: generated=False requires explicit key"
                    )
                element.key = None

                return self.generate_key(element, session)

            persisted = session.get(self._model, pk)

            if persisted is None:
                if self.generated:
                    element.key = None

                return self.generate_key(element, session)

            for f in dataclasses.fields(element):
                if f.name == "key":
                    continue
                setattr(persisted, f.name, getattr(element, f.name))

            return pk

    def retrieve(self, key: int) -> Optional[TElement]:
        with self._session_factory() as session:
            return session.get(self._model, key)

    def delete_by(self, column: Mapped, value) -> None:
        with self._session_factory() as session, session.begin():
            stmt = delete(self._model).where(column == value)
            session.execute(stmt)

    def delete(self, key: int) -> None:
        self.delete_by(self._model.key, key)

    def count(self) -> int:
        with self._session_factory() as session:
            return session.scalar(
                select(func.count()).select_from(self._model)
            ) or 0

    def count_filtered(self, **filters: Any) -> int:
        model = cast(Any, self._model)
        stmt = select(func.count()).select_from(model)
        for name, value in filters.items():
            stmt = stmt.where(getattr(model, name) == value)
        with self._session_factory() as session:
            return session.scalar(stmt) or 0